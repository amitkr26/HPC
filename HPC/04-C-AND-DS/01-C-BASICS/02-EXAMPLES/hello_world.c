/*
 * Question: Write a C program to print "Hello" and "World".
 * Answer:   printf("Hello\n") prints on one line; printf("World") prints without
 *           a newline, so the output is:
 *           Hello
 *           World
 */
#include<stdio.h>
int main()
{
    printf("Hello\n");
    printf("World");
    return 0;
}